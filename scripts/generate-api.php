<?php

use Google\Client;
use Google\Service\Resource;

/**
 * Generates typed wrappers for every resource method of the supported Google APIs
 * from the installed google/apiclient-services package.
 *
 *   composer generate-api
 *
 * Output: src/Api/{Service}Api.php, src/Api/{Service}/*Resource.php and src/Api/manifest.php.
 * Re-run after updating google/apiclient-services to pick up new endpoints.
 */

require __DIR__.'/../vendor/autoload.php';

const SERVICES = [
    // Google service class => [wrapper name, service name used in logs/errors]
    'Directory' => ['Directory', 'directory'],
    'Classroom' => ['Classroom', 'classroom'],
    'Calendar' => ['Calendar', 'calendar'],
    'Gmail' => ['Gmail', 'gmail'],
    'Drive' => ['Drive', 'drive'],
];

const RESERVED = ['call', 'paginate', '__construct', 'items', 'identifier'];

$root = dirname(__DIR__);
$outDir = $root.'/src/Api';
$version = installedVersion($root, 'google/apiclient-services');
$manifest = ['version' => $version, 'services' => []];

foreach (SERVICES as $googleName => [$name, $serviceName]) {
    $serviceClass = "Google\\Service\\{$googleName}";
    $service = new $serviceClass(new Client);

    $resources = [];
    foreach ((new ReflectionObject($service))->getProperties(ReflectionProperty::IS_PUBLIC) as $property) {
        $value = $property->getValue($service);
        if (! $value instanceof Google\Service\Resource) {
            continue;
        }

        $methods = resourceMethods($value);
        if ($methods) {
            $resources[$property->getName()] = ['class' => get_class($value), 'methods' => $methods, 'object' => $value];
        }
    }
    ksort($resources);

    @mkdir("{$outDir}/{$name}", 0777, true);
    foreach (glob("{$outDir}/{$name}/*Resource.php") as $old) {
        unlink($old);
    }

    foreach ($resources as $property => $resource) {
        $class = shortName($resource['class']).'Resource';
        file_put_contents("{$outDir}/{$name}/{$class}.php", resourceFile($name, $class, $resource, $version));
        $manifest['services'][$serviceName][$property] = array_keys($resource['methods']);
    }

    file_put_contents("{$outDir}/{$name}Api.php", serviceFile($name, $serviceClass, $resources, $version));
    printf("%-10s %3d resources, %3d methods\n", $name, count($resources), array_sum(array_map(fn ($r) => count($r['methods']), $resources)));
}

file_put_contents("{$outDir}/manifest.php", "<?php\n\n// @generated by scripts/generate-api.php - do not edit\n\nreturn ".exportArray($manifest).";\n");

